"""Deterministically generate *synthetic* Collection WAV bytes, never HPC recordings.

Run: python scripts/generate_example_collection.py --write --output /tmp/collection
To revise the tracked demo (with review): ... --write --output tests/data/example_collection
Existing files are never replaced without --replace.
"""

from __future__ import annotations

import argparse
import struct
import wave
from pathlib import Path

RATE = 16_000
DURATION_SECONDS = 8
# Recorded source-time in integer milliseconds; exact 1-second excerpts.
EXAMPLES = (
    ("REC_A", 1000, 2000, "callA", 73, 317),
    ("REC_B", 3000, 4000, "callB", 109, 241),
    ("REC_C", 5000, 6000, "callC", 137, 193),
)


def build_wave_bytes(period_a: int, period_b: int) -> bytes:
    """Integer-only triangle signals: platform-invariant PCM16 generated bytes."""
    frames = bytearray()
    for frame in range(RATE * DURATION_SECONDS):
        a = abs((frame % period_a) * 2 - period_a) - period_a // 2
        b = abs((frame % period_b) * 2 - period_b) - period_b // 2
        value = max(-32768, min(32767, a * 43 + b * 21))
        frames.extend(struct.pack("<h", value))
    return bytes(frames)


def write_wave(path: Path, frames: bytes, replace: bool) -> None:
    if path.exists() and not replace:
        raise FileExistsError(f"Refusing to overwrite {path}; pass --replace deliberately")
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as target:
        target.setnchannels(1)
        target.setsampwidth(2)
        target.setframerate(RATE)
        target.writeframes(frames)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Explicitly generate WAVs")
    parser.add_argument("--output", type=Path, help="Collection root, never an HPC path")
    parser.add_argument("--replace", action="store_true", help="Allow overwriting existing WAVs")
    args = parser.parse_args()
    if not args.write or args.output is None:
        parser.error("--write and --output are required")
    root = args.output
    expected = []
    for source, start_ms, end_ms, label, period_a, period_b in EXAMPLES:
        expected.extend(
            [
                root / "recordings" / f"{source}.wav",
                root
                / "positives"
                / f"{source}__start-{start_ms:05d}ms__end-{end_ms:05d}ms__{label}.wav",
            ]
        )
    if not args.replace:
        exists = [str(path) for path in expected if path.exists()]
        if exists:
            parser.error("Refusing to overwrite existing files: " + ", ".join(exists))
    for source, start_ms, end_ms, label, period_a, period_b in EXAMPLES:
        frames = build_wave_bytes(period_a, period_b)
        write_wave(root / "recordings" / f"{source}.wav", frames, args.replace)
        a = start_ms * RATE // 1000 * 2
        b = end_ms * RATE // 1000 * 2
        write_wave(
            root
            / "positives"
            / f"{source}__start-{start_ms:05d}ms__end-{end_ms:05d}ms__{label}.wav",
            frames[a:b],
            args.replace,
        )
    print(f"Generated {len(expected)} synthetic PCM16 mono 16-kHz WAVs in {root}")


if __name__ == "__main__":
    main()
